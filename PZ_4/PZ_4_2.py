# Дано целое число N (>1)
# Вывести наибольшее K, для котрого суммв 1 + 2 + ... + К <=N, и саму эту сумму.
while True:
    try:
        n = int(input("Введите число N: "))
        if n > 1:
            break
        else:
            print("Число должное быть больше 1.")
    except ValueError:
        print("Введите правильное число")
k = 0
s = 0
while s + k + 1 <= n:
    k += 1
    s += k
print("Наибольшее число K:", k)
print("Сумма чисел:", s)