#Состаыить программу, в которой функцию построит изображение, в которомв первой строке звёздочка,
#во второй - 2, в третей-3, в строке m - m звёздочек.
def print_stars(m):
    i = 1
    while i <= m:
        print("*" * i)
        i += 1
m = input("Введите количество строк: ")
while type(m) != int:
    try:
        m = int(m)
    except ValueError:
        print("Непавильно ввели!")
        m = input("Введите количество строк: ")
print_stars(m)